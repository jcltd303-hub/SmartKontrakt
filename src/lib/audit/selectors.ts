const bySelector = new Map<string, string>();
for (const sig of SIGNATURES) {
  const sel = keccak256(sig).slice(0, 8);
  if (!bySelector.has(sel)) bySelector.set(sel, sig);
}

export function lookupSelector(hex8: string): string | null {
  return bySelector.get(hex8.toLowerCase()) ?? null;
}

export function knownSelectors(): Map<string, string> {
  return bySelector;
}
